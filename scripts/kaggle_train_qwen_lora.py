"""Kaggle T4 GPU LoRA SFT trainer & frozen query-plan cache exporter for Qwen2.5-1.5B-Instruct.

Supports:
- Full Kaggle T4 GPU LoRA SFT training using transformers + peft + torch (FP16/BF16 or optional 4-bit)
  on ChatML JSONL generated by scripts/prepare_qwen_sft_dataset.py.
- Exporting `query_plan_cache.jsonl` + `qwen_receipt.json` compatible with
  `AdaptiveQueryDecomposer.from_frozen_llm_cache` / `AdaptiveQueryDecomposer(query_plan_cache=..., prompt_version=...)`
  and `scripts/capture_msr_candidate_pools.py`.
- `--dry-run` on CPU (no GPU or HuggingFace weights download required) that runs the
  ChatML formatting, tokenization, label masking, and SemanticDecomposerValidator loop
  on synthetic/mock samples and writes `lora_config.json`, `query_plan_cache.jsonl`,
  and `qwen_receipt.json` for CI verification.
"""
