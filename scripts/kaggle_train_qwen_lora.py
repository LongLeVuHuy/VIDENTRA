class _DryRunTokenizer:
    """Deterministic whitespace/token-level tokenizer for CPU --dry-run without HF downloads."""

    pad_token_id = 0
    eos_token_id = 2

    def encode(self, text: str, add_special_tokens: bool = False) -> list[int]:
        if not text:
            return []
        return [10 + (len(tok) % 29000) for tok in text.split()]

    def apply_chat_template(
        self,
        messages: list[dict[str, str]],
        tokenize: bool = False,
        add_generation_prompt: bool = False,
    ) -> str:
        parts: list[str] = []
        for msg in messages:
            parts.append(f"<|im_start|>{msg['role']}\n{msg['content']}<|im_end|>\n")
        if add_generation_prompt:
            parts.append("<|im_start|>assistant\n")
        rendered = "".join(parts)
        return self.encode(rendered) if tokenize else rendered


def format_and_tokenize_chatml(
    messages: list[dict[str, str]],
    tokenizer: Any,
    max_seq_len: int = 512,
) -> dict[str, list[int]]:
    """Format ChatML messages and mask prompt tokens (-100) so loss applies only to assistant JSON."""
    prompt_messages = [m for m in messages if m.get("role") != "assistant"]
    assistant_content = next(
        (str(m.get("content", "")) for m in messages if m.get("role") == "assistant"),
        "",
    )
    if not assistant_content:
        raise ValueError("SFT record missing assistant content")

    if hasattr(tokenizer, "apply_chat_template"):
        prompt_text = tokenizer.apply_chat_template(
            prompt_messages, tokenize=False, add_generation_prompt=True
        )
        full_text = tokenizer.apply_chat_template(
            [*prompt_messages, {"role": "assistant", "content": assistant_content}],
            tokenize=False,
            add_generation_prompt=False,
        )
        prompt_ids = list(tokenizer.encode(prompt_text, add_special_tokens=False))
        full_ids = list(tokenizer.encode(full_text, add_special_tokens=False))
    else:
        prompt_text = "".join(
            f"<|im_start|>{m['role']}\n{m['content']}<|im_end|>\n" for m in prompt_messages
        ) + "<|im_start|>assistant\n"
        full_text = f"{prompt_text}{assistant_content}<|im_end|>\n"
        prompt_ids = list(tokenizer.encode(prompt_text))
        full_ids = list(tokenizer.encode(full_text))

    full_ids = full_ids[:max_seq_len]
    prompt_len = min(len(prompt_ids), len(full_ids))
    labels = [-100] * prompt_len + full_ids[prompt_len:]
    attention_mask = [1] * len(full_ids)
    return {
        "input_ids": full_ids,
        "attention_mask": attention_mask,
        "labels": labels,
    }


def _load_sft_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.is_file():
        raise FileNotFoundError(f"SFT JSONL not found: {path}")
    rows: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as fh:
        for line_no, line in enumerate(fh, start=1):
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            if not isinstance(row, dict) or not isinstance(row.get("messages"), list):
                raise ValueError(f"Invalid SFT record at {path}:{line_no}")
            rows.append(row)
    if not rows:
        raise ValueError(f"Empty SFT dataset: {path}")
    return rows


def _load_export_queries(queries_path: Path | None, dry_run: bool) -> list[dict[str, str]]:
    if queries_path is None:
        if dry_run:
            return [
                {"query_id": f"dry_{i}", "dataset": "synthetic", "query_text": q}
                for i, q in enumerate(DRY_RUN_SYNTHETIC_QUERIES, start=1)
            ]
        return []
    if not queries_path.is_file():
        raise FileNotFoundError(f"Export queries JSONL not found: {queries_path}")
    rows: list[dict[str, str]] = []
    with queries_path.open("r", encoding="utf-8") as fh:
        for idx, line in enumerate(fh, start=1):
            line = line.strip()
            if not line:
                continue
            item = json.loads(line)
            q_text = str(item.get("query_text") or item.get("query") or "").strip()
            if not q_text:
                continue
            rows.append(
                {
                    "query_id": str(item.get("query_id") or item.get("qid") or f"q_{idx}"),
                    "dataset": str(item.get("dataset") or "custom"),
                    "query_text": q_text,
                }
            )
    return rows


def _make_cache_key(query: str, model_revision: str, prompt_version: str) -> str:
    nfc = unicodedata.normalize("NFC", query.strip())
    raw = f"{nfc}|{model_revision}|{prompt_version}"
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def export_query_plan_cache(
    queries: Sequence[dict[str, str]],
    cache_path: Path,
    generate_fn: Callable[[str], str],
    model_revision: str,
    prompt_version: str,
) -> dict[str, int]:
    """Run generation + SemanticDecomposerValidator and write AdaptiveQueryDecomposer-compatible JSONL."""
    gate = QueryComplexityGate()
    validator = SemanticDecomposerValidator()
    records_by_key: dict[str, dict[str, Any]] = {}
    valid_count = 0
    rejected_count = 0

    for item in queries:
        norm_query = unicodedata.normalize("NFC", item["query_text"].strip())
        if not norm_query:
            continue
        decision = gate.classify(norm_query)
        try:
            raw_resp = generate_fn(norm_query)
            json_str = _extract_json_block(raw_resp)
            data = json.loads(json_str)
            for ev in data.get("events") or []:
                if is_generic_placeholder_clause(str(ev.get("vis") or "")):
                    raise ValueError("Rejected generic placeholder clause in exported plan")
            _, plan = validator.validate_and_expand(
                data,
                original_query=norm_query,
                query_length_tier=decision.tier,
                routing_mode="llm_compact",
                model_revision=model_revision,
                prompt_version=prompt_version,
            )
            key = _make_cache_key(norm_query, model_revision=model_revision, prompt_version=prompt_version)
            q_sha = hashlib.sha256(plan.original_query.encode("utf-8")).hexdigest()
            records_by_key[key] = {
                "key": key,
                "model_revision": model_revision,
                "prompt_version": prompt_version,
                "query_text_sha256": q_sha,
                "plan": plan.to_dict(),
            }
            valid_count += 1
        except Exception:
            rejected_count += 1

    _atomic_write_jsonl(cache_path, list(records_by_key.values()))
    return {
        "total_queries": len(queries),
        "exported_records": len(records_by_key),
        "valid_plan_count": valid_count,
        "rejected_count": rejected_count,
    }


def _train_live_lora(
    train_rows: list[dict[str, Any]],
    val_rows: list[dict[str, Any]],
    args: argparse.Namespace,
    lora_cfg_dict: dict[str, Any],
) -> tuple[Any, Any]:
    """Run actual Qwen2.5-1.5B-Instruct LoRA SFT on GPU using transformers + peft."""
    from peft import LoraConfig, TaskType, get_peft_model, prepare_model_for_kbit_training  # type: ignore
    from transformers import (  # type: ignore
        AutoModelForCausalLM,
        AutoTokenizer,
        DataCollatorForSeq2Seq,
        Trainer,
        TrainingArguments,
    )

    tokenizer = AutoTokenizer.from_pretrained(
        args.base_model,
        revision=args.base_revision,
        trust_remote_code=False,
    )
    if tokenizer.pad_token_id is None:
        tokenizer.pad_token = tokenizer.eos_token

    model_kwargs: dict[str, Any] = {
        "revision": args.base_revision,
        "trust_remote_code": False,
    }
    if args.load_in_4bit:
        from transformers import BitsAndBytesConfig  # type: ignore

        compute_dtype = torch.bfloat16 if args.bf16 else torch.float16
        model_kwargs["quantization_config"] = BitsAndBytesConfig(
            load_in_4bit=True,
            bnb_4bit_quant_type="nf4",
            bnb_4bit_use_double_quant=True,
            bnb_4bit_compute_dtype=compute_dtype,
        )
        model_kwargs["device_map"] = "auto"
    else:
        model_kwargs["torch_dtype"] = (
            torch.bfloat16 if args.bf16 else (torch.float16 if args.fp16 else torch.float32)
        )
        if torch.cuda.is_available():
            model_kwargs["device_map"] = "auto"

    model = AutoModelForCausalLM.from_pretrained(args.base_model, **model_kwargs)
    if args.load_in_4bit:
        model = prepare_model_for_kbit_training(model)

    peft_config = LoraConfig(
        task_type=TaskType.CAUSAL_LM,
        r=lora_cfg_dict["r"],
        lora_alpha=lora_cfg_dict["lora_alpha"],
        lora_dropout=lora_cfg_dict["lora_dropout"],
        target_modules=list(lora_cfg_dict["target_modules"]),
        bias=lora_cfg_dict["bias"],
    )
    model = get_peft_model(model, peft_config)

    train_features = [format_and_tokenize_chatml(r["messages"], tokenizer, args.max_seq_len) for r in train_rows]
    val_features = [format_and_tokenize_chatml(r["messages"], tokenizer, args.max_seq_len) for r in val_rows]

    class _ListDataset(torch.utils.data.Dataset):
        def __init__(self, items: list[dict[str, list[int]]]) -> None:
            self.items = items

        def __len__(self) -> int:
            return len(self.items)

        def __getitem__(self, idx: int) -> dict[str, list[int]]:
            return self.items[idx]

    adapter_dir = args.output_dir / "lora_adapter"
    train_args = TrainingArguments(
        output_dir=str(args.output_dir / "checkpoints"),
        num_train_epochs=args.epochs,
        per_device_train_batch_size=args.batch_size,
        per_device_eval_batch_size=args.batch_size,
        gradient_accumulation_steps=args.grad_accum,
        learning_rate=args.lr,
        fp16=bool(args.fp16 and not args.bf16),
        bf16=bool(args.bf16),
        logging_steps=10,
        eval_strategy="epoch" if val_features else "no",
        save_strategy="epoch",
        save_total_limit=1,
        seed=args.seed,
        report_to="none",
        remove_unused_columns=False,
    )
    collator = DataCollatorForSeq2Seq(tokenizer=tokenizer, padding=True, label_pad_token_id=-100)
    trainer = Trainer(
        model=model,
        args=train_args,
        train_dataset=_ListDataset(train_features),
        eval_dataset=_ListDataset(val_features) if val_features else None,
        data_collator=collator,
    )
    trainer.train()
    adapter_dir.mkdir(parents=True, exist_ok=True)
    model.save_pretrained(str(adapter_dir))
    tokenizer.save_pretrained(str(adapter_dir))
    return model, tokenizer


def run_training_pipeline(args: argparse.Namespace) -> dict[str, Any]:
    """Execute LoRA SFT (or CPU --dry-run) and optionally export frozen query_plan_cache.jsonl."""
    torch.manual_seed(args.seed)
    args.output_dir.mkdir(parents=True, exist_ok=True)

    train_jsonl = args.train_jsonl
    val_jsonl = args.val_jsonl
    if args.dry_run and (train_jsonl is None or not train_jsonl.exists()):
        synth_dir = args.output_dir / "dry_run_sft_data"
        build_sft_dataset(
            output_dir=synth_dir,
            num_samples=16,
            val_ratio=0.25,
            seed=args.seed,
            prompt_version=args.prompt_version,
        )
        train_jsonl = synth_dir / "sft_train.jsonl"
        val_jsonl = synth_dir / "sft_val.jsonl"

    if train_jsonl is None:
        raise ValueError("--train-jsonl is required unless --dry-run generates synthetic data")

    train_rows = _load_sft_jsonl(train_jsonl)
    val_rows = _load_sft_jsonl(val_jsonl) if (val_jsonl is not None and val_jsonl.exists()) else []

    lora_cfg_dict = {
        "peft_type": "LORA",
        "task_type": "CAUSAL_LM",
        "base_model_name_or_path": args.base_model,
        "base_model_revision": args.base_revision,
        "r": args.lora_r,
        "lora_alpha": args.lora_alpha,
        "lora_dropout": args.lora_dropout,
        "bias": "none",
        "target_modules": list(LORA_TARGET_MODULES),
    }
    _atomic_write_json(args.output_dir / "lora_config.json", lora_cfg_dict)

    if args.dry_run:
        tokenizer = _DryRunTokenizer()
        tokenized_train = [
            format_and_tokenize_chatml(row["messages"], tokenizer, max_seq_len=args.max_seq_len)
            for row in train_rows
        ]
        tokenized_val = [
            format_and_tokenize_chatml(row["messages"], tokenizer, max_seq_len=args.max_seq_len)
            for row in val_rows
        ]
        # Verify tensor shapes and unmasked assistant tokens on CPU
        for feat in tokenized_train:
            ids_t = torch.tensor(feat["input_ids"], dtype=torch.long)
            labels_t = torch.tensor(feat["labels"], dtype=torch.long)
            if ids_t.shape != labels_t.shape or int((labels_t != -100).sum().item()) == 0:
                raise RuntimeError("Dry-run tokenization produced invalid input_ids/labels alignment")

        rule_parser = RuleBasedQueryParser()

        def _mock_generate(query: str) -> str:
            wire = _extract_wire_from_rule_parser(query, rule_parser)
            return json.dumps(wire, ensure_ascii=False)

        generate_fn: Callable[[str], str] = _mock_generate
        token_stats = {
            "train_tokenized": len(tokenized_train),
            "val_tokenized": len(tokenized_val),
            "mean_train_tokens": round(
                sum(len(f["input_ids"]) for f in tokenized_train) / max(1, len(tokenized_train)), 2
            ),
        }
    else:
        model, tokenizer = _train_live_lora(train_rows, val_rows, args, lora_cfg_dict)
        model.eval()
        sys_prompt = get_sft_system_prompt(args.prompt_version)

        def _live_generate(query: str) -> str:
            messages = [
                {"role": "system", "content": sys_prompt},
                {"role": "user", "content": query},
            ]
            prompt_text = tokenizer.apply_chat_template(
                messages, tokenize=False, add_generation_prompt=True
            )
            inputs = tokenizer([prompt_text], return_tensors="pt").to(model.device)
            with torch.no_grad():
                outputs = model.generate(
                    **inputs,
                    max_new_tokens=args.max_new_tokens,
                    do_sample=False,
                    pad_token_id=tokenizer.eos_token_id,
                )
            gen_ids = outputs[0][inputs["input_ids"].shape[1] :]
            return str(tokenizer.decode(gen_ids, skip_special_tokens=True))

        generate_fn = _live_generate
        token_stats = {"train_tokenized": len(train_rows), "val_tokenized": len(val_rows)}

    export_queries = _load_export_queries(args.export_cache_queries, dry_run=args.dry_run)
    cache_path = args.cache_output or (args.output_dir / "query_plan_cache.jsonl")
    cache_stats = {"total_queries": 0, "exported_records": 0, "valid_plan_count": 0, "rejected_count": 0}
    cache_sha256: str | None = None
    if export_queries:
        cache_stats = export_query_plan_cache(
            queries=export_queries,
            cache_path=cache_path,
            generate_fn=generate_fn,
            model_revision=args.model_revision,
            prompt_version=args.prompt_version,
        )
        cache_sha256 = _sha256_file(cache_path)

    receipt = {
        "schema_version": "1.0",
        "dry_run": bool(args.dry_run),
        "base_model": args.base_model,
        "base_revision": args.base_revision,
        "model_revision": args.model_revision,
        "prompt_version": args.prompt_version,
        "train_jsonl": str(train_jsonl),
        "val_jsonl": str(val_jsonl) if val_jsonl else None,
        "train_samples": len(train_rows),
        "val_samples": len(val_rows),
        "token_stats": token_stats,
        "lora_config": lora_cfg_dict,
        "training_args": {
            "epochs": args.epochs,
            "batch_size": args.batch_size,
            "grad_accum": args.grad_accum,
            "lr": args.lr,
            "max_seq_len": args.max_seq_len,
            "fp16": bool(args.fp16),
            "bf16": bool(args.bf16),
            "load_in_4bit": bool(args.load_in_4bit),
            "seed": args.seed,
        },
        "cache_export": {
            **cache_stats,
            "cache_path": str(cache_path) if export_queries else None,
            "cache_sha256": cache_sha256,
        },
    }
    _atomic_write_json(args.output_dir / "qwen_receipt.json", receipt)
    return receipt


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Kaggle T4 LoRA SFT training and query_plan_cache.jsonl exporter for Qwen2.5-1.5B-Instruct."
    )
    parser.add_argument("--train-jsonl", type=Path, default=None, help="Path to sft_train.jsonl")
    parser.add_argument("--val-jsonl", type=Path, default=None, help="Path to sft_val.jsonl")
    parser.add_argument("--output-dir", type=Path, default=Path("work/qwen_lora_sft"))
    parser.add_argument("--base-model", type=str, default=BASE_MODEL_ID)
    parser.add_argument("--base-revision", type=str, default=BASE_MODEL_REVISION)
    parser.add_argument("--model-revision", type=str, default=DEFAULT_MODEL_REVISION)
    parser.add_argument("--prompt-version", type=str, default=DEFAULT_PROMPT_VERSION)
    parser.add_argument("--epochs", type=int, default=3)
    parser.add_argument("--batch-size", type=int, default=4)
    parser.add_argument("--grad-accum", type=int, default=4)
    parser.add_argument("--lr", type=float, default=2e-4)
    parser.add_argument("--max-seq-len", type=int, default=768)
    parser.add_argument("--max-new-tokens", type=int, default=160)
    parser.add_argument("--lora-r", type=int, default=16)
    parser.add_argument("--lora-alpha", type=int, default=32)
    parser.add_argument("--lora-dropout", type=float, default=0.05)
    parser.add_argument("--fp16", action="store_true", default=True)
    parser.add_argument("--no-fp16", dest="fp16", action="store_false")
    parser.add_argument("--bf16", action="store_true", default=False)
    parser.add_argument("--load-in-4bit", action="store_true", default=False)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--export-cache-queries",
        type=Path,
        default=None,
        help="Optional GT-free queries JSONL to export validated query_plan_cache.jsonl.",
    )
    parser.add_argument("--cache-output", type=Path, default=None)
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="CPU-only CI verification without HF downloads or GPU training.",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    receipt = run_training_pipeline(args)
    print(
        f"Qwen LoRA SFT {'DRY-RUN ' if receipt['dry_run'] else ''}complete: "
        f"train={receipt['train_samples']}, val={receipt['val_samples']}, "
        f"exported_cache={receipt['cache_export']['exported_records']} -> {args.output_dir}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
